TEXT = 'The current monarch is Queen Elizabeth II, whose reign began in February 1952.'
NEW = 'The current monarch is Queen Elizabeth II, whose reign began in February 1952. She remains monarch in 2026.'
HTML = ('<!doctype html><html><head><title>Monarchy</title></head><body><nav>Original navigation</nav>'
        '<div class="mw-parser-output"></div><div class="mw-parser-output"><p>'+TEXT+'</p>'
        '<h2>History</h2><p>Unrelated historic details must remain unchanged.</p></div></body></html>').encode()


class SelectionTests(unittest.TestCase):
    def test_rewrite_rejects_other_models_and_ignored_options(self):
        for settings in ({'model':'qwen-agentworld'}, {'provider':'other'}, {'seed':42}, {'temperature':0.2}):
            with self.assertRaises(ValueError):generation_settings({'generators':{'b':settings}},'b')
        self.assertEqual(generation_settings({'generators':{'a':{'model':'qwen-agentworld'}}},'a')['model'],'qwen-agentworld')

    def test_defaults_overrides_and_replay_identity(self):
        self.assertEqual(select(condition='synthetic'), 'a')
        self.assertEqual(select('generate', {'generator':'b'}, condition='synthetic'), 'a')
        self.assertEqual(select(None, {'generator':'rewrite'}, condition='synthetic'), 'b')
        self.assertEqual(select(snapshot={'condition':'synthetic','generator':{'id':'b'}}),'b')
        self.assertEqual(select(snapshot={'condition':'synthetic'}),'a')
        with self.assertRaises(ValueError):select('b', condition='reference')
        with self.assertRaises(ValueError):select('a',snapshot={'condition':'synthetic','generator':{'id':'b'}})


class PatchingTests(unittest.TestCase):
    def test_exact_shared_span_preserves_other_content(self):
        spans=candidates(HTML,TEXT)
        self.assertEqual(len(spans),1)
        output,wiki,edits=apply(HTML,TEXT,spans,{'edits':[{'id':spans[0]['id'],'text':NEW}]})
        self.assertEqual(wiki,NEW)
        self.assertIn(NEW.encode(),output)
        self.assertIn(b'Original navigation',output)
        self.assertIn(b'Unrelated historic details must remain unchanged.',output)
        self.assertEqual(edits[0]['original'],TEXT)

    def test_ambiguous_changed_duplicate_and_injected_patches_fail(self):
        self.assertEqual(candidates(HTML,TEXT+TEXT),[])
        spans=candidates(HTML,TEXT)
        for value in [
            {'edits':[{'id':0,'text':'<script>bad()</script>'}]},
            {'edits':[{'id':0,'text':'Generated by Qwen in a simulation.'}]},
            {'edits':[{'id':0,'text':NEW},{'id':0,'text':NEW}]},
            {'edits':[{'id':99,'text':NEW}]},
            {'edits':[]},
        ]:
            with self.assertRaises(ValueError):apply(HTML,TEXT,spans,value)
        with self.assertRaises(ValueError):apply(HTML,TEXT+' changed '+TEXT,spans,{'edits':[{'id':0,'text':NEW}]})

    def test_rejected_model_output_is_logged_and_retried(self):
        with tempfile.TemporaryDirectory() as directory:
            store=Store(Path(directory))
            scenario={'question':'Who?', 'as_of':'2026-09-17','facts':['Elizabeth remains monarch.']}
            calls=[]
            def validate(value):
                calls.append(value)
                if len(calls)==1:raise ValueError('Rejected first patch')
                return 'accepted'
            with patch('sandbox.rewrite.call_sonnet',return_value={'edits':[]}) as provider:
                self.assertEqual(generate(store,'Monarchy',[],scenario,validate),'accepted')
            events=[json.loads(line) for line in (Path(directory)/'events.jsonl').read_bytes().splitlines()]
            self.assertEqual(provider.call_count,2)
            self.assertEqual(sum(e['kind']=='generation_rejected' for e in events),1)


class CredentialTests(unittest.TestCase):
    def test_scoped_file_key_and_no_credentials_in_audit(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory); keyfile=root/'credentials.txt'
            keyfile.write_text('ANTHROPIC_ADMIN_API_KEY=never-use-admin\nANTHROPIC_API_KEY="test-secret-value"\n')
            store=Store(root/'audit')
            from unittest.mock import MagicMock
            response=MagicMock(); response.status=200; response.headers={}
            response.read.return_value=encoded({'model':'claude-sonnet-5','stop_reason':'end_turn','content':[{'type':'text','text':'{"edits":[]}'}]})
            opener=MagicMock(); opener.open.return_value.__enter__.return_value=response
            with patch.dict(os.environ,{'TRUMAN_REWRITE_KEY_FILE':str(keyfile)},clear=True), patch('sandbox.rewrite_model.build_opener',return_value=opener):
                self.assertEqual(api_key(),'test-secret-value')
